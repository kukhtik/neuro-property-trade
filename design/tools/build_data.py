#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the design package's data from the GAME (single source of truth).

Reads (read-only):
  game/data/board.json          board tiles: names, groups, costs, rents
  game/i18n/data_*.gd           the full RU/EN dictionary (keys -> {ru,en})
  game/assets/skins/*/skin.json palettes, sizes, metrics, motion

Writes:
  design/i18n.json              {key: {"ru": ..., "en": ...}}
  design/src/data.js            window.NPT_DATA = {board, i18n, skins}

Nothing here is hand-typed: the prototype must show the game's REAL names,
numbers and strings. Re-run after any game-data change:

    python design/tools/build_data.py
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]      # repo root
GAME = ROOT / "game"
OUT = ROOT / "design"
SKINS = ["default", "neuro", "evil", "classic"]

ENTRY = re.compile(
    r'"((?:[^"\\]|\\.)*)"\s*:\s*\{\s*'
    r'"ru"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,\s*'
    r'"en"\s*:\s*"((?:[^"\\]|\\.)*)"\s*\}',
    re.DOTALL,
)
KEYHEAD = re.compile(r'"((?:[^"\\]|\\.)*)"\s*:\s*\{')

ESC = {
    "n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'", "/": "/",
}


def unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "u":
                m = re.match(r"u([0-9a-fA-F]{4})", s[i + 2:])
                if m:
                    out.append(chr(int(m.group(1), 16)))
                    i += 6
                    continue
            if n in ESC:
                out.append(ESC[n])
                i += 2
                continue
        out.append(c)
        i += 1
    return "".join(out)


def parse_i18n() -> tuple[dict, dict, list, list]:
    # Merged in the SAME order as game/i18n/i18n.gd `_FILES`, with overwrite
    # (`merge(d, true)`) — a later file wins on a duplicate key. The phase.*
    # keys live in BOTH data_ui and data_settings; i18n.gd's winner is the
    # data_settings copy.
    order = [
        "data_ui.gd", "data_settings.gd", "data_action.gd",
        "data_event.gd", "data_admin.gd",
    ]
    merged: dict = {}
    anomalies: list = []
    per_file: dict = {}
    dup_notes: list = []
    for name in order:
        path = GAME / "i18n" / name
        if not path.exists():
            anomalies.append(f"{name}: missing")
            continue
        text = path.read_text(encoding="utf-8")
        found = {}
        for m in ENTRY.finditer(text):
            found[unescape(m.group(1))] = {
                "ru": unescape(m.group(2)),
                "en": unescape(m.group(3)),
            }
        # every key-shaped head must have been captured as a full entry
        for m in KEYHEAD.finditer(text):
            if m.group(1) not in found:
                anomalies.append(f"{name}: uncaptured key head {m.group(1)!r}")
        for k, v in found.items():
            if k in merged:
                if merged[k] != v:
                    dup_notes.append(f"{name}: {k} overrides a DIFFERENT value")
                else:
                    dup_notes.append(f"{name}: {k} (identical copy)")
        merged.update(found)
        per_file[name] = len(found)
    return merged, per_file, anomalies, dup_notes


def read_skins() -> dict:
    out = {}
    for sid in SKINS:
        path = GAME / "assets" / "skins" / sid / "skin.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        out[sid] = {
            "id": data.get("id", sid),
            "name": data.get("name", sid),
            "name_ru": data.get("name_ru", data.get("name", sid)),
            "extends": data.get("extends"),
            "tokens": data.get("tokens", {}),
            "metrics": data.get("metrics", {}),
            "motion": data.get("motion", {}),
            "slots": sorted((data.get("slots") or {}).keys()),
            "assets": sorted((data.get("assets") or {}).keys()),
        }
    return out


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "src").mkdir(parents=True, exist_ok=True)

    board = json.loads((GAME / "data" / "board.json").read_text(encoding="utf-8"))
    i18n, per_file, anomalies, dup_notes = parse_i18n()
    skins = read_skins()

    (OUT / "i18n.json").write_text(
        json.dumps(i18n, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    payload = {
        "board": board,
        "i18n": i18n,
        "skins": skins,
    }
    data_js = (
        "// GENERATED by design/tools/build_data.py — do not edit by hand.\n"
        "// Sources: game/data/board.json, game/i18n/data_*.gd, game/assets/skins/*/skin.json\n"
        "window.NPT_DATA = "
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    (OUT / "src" / "data.js").write_text(data_js, encoding="utf-8")

    print(f"board tiles: {len(board.get('tiles', []))} (meta: {board.get('meta', {})})")
    print(f"i18n keys : {len(i18n)}  per file: {per_file}")
    print(f"skins     : {list(skins.keys())}")
    for d in dup_notes:
        print("  dup  " + d)
    no_en = [k for k, v in i18n.items() if not v["en"]]
    no_ru = [k for k, v in i18n.items() if not v["ru"]]
    if no_en:
        print(f"  WARN keys missing EN: {no_en[:10]}")
    if no_ru:
        print(f"  WARN keys missing RU: {no_ru[:10]}")
    for a in anomalies:
        print("  ANOMALY " + a)
    if anomalies:
        return 1
    print(f"wrote {OUT / 'i18n.json'} and {OUT / 'src' / 'data.js'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
